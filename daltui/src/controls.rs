//! Control tables for the three subsystems. The UI renders these generically;
//! `Sim` (and later a real backend) interprets the `id`.

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Sub {
    Obc,
    Exp,
    Pdu,
}

impl Sub {
    pub const ALL: [Sub; 3] = [Sub::Obc, Sub::Exp, Sub::Pdu];

    pub fn idx(self) -> usize {
        self as usize
    }
    pub fn name(self) -> &'static str {
        match self {
            Sub::Obc => "OBC",
            Sub::Exp => "EXP",
            Sub::Pdu => "PDU",
        }
    }
    pub fn pages(self) -> &'static [&'static str] {
        match self {
            Sub::Obc => &["Overview", "Camera"],
            Sub::Exp => &[
                "Overview",
                "Pump U11",
                "Pump U15",
                "Motors",
                "IR LEDs",
                "Burn wire",
                "Crystallization",
                "Heaters",
                "IR Camera",
            ],
            Sub::Pdu => &["Overview"],
        }
    }
    pub fn controls(self, page: usize) -> &'static [Control] {
        match (self, page) {
            (Sub::Obc, 0) => OBC_MAIN,
            (Sub::Obc, _) => OBC_CAM,
            (Sub::Exp, 0) => EXP_MAIN,
            (Sub::Exp, 1) => EXP_U11,
            (Sub::Exp, 2) => EXP_U15,
            (Sub::Exp, 3) => EXP_MOTOR,
            (Sub::Exp, 4) => EXP_IR,
            (Sub::Exp, 5) => EXP_BURN,
            (Sub::Exp, 6) => EXP_PC,
            (Sub::Exp, 7) => EXP_HEATER,
            (Sub::Exp, _) => EXP_CAMERA,
            (Sub::Pdu, _) => PDU,
        }
    }
}

pub enum Kind {
    Toggle,
    Step {
        min: i32,
        max: i32,
        _step: i32,
        unit: &'static str,
    },
    Choice(&'static [&'static str]),
    Action,
    /// Needs a second confirmation before it runs.
    Danger,
}

pub struct Control {
    pub group: &'static str,
    pub id: &'static str,
    pub label: &'static str,
    pub kind: Kind,
    pub hint: &'static str,
}

const fn c(
    group: &'static str,
    id: &'static str,
    label: &'static str,
    kind: Kind,
    hint: &'static str,
) -> Control {
    Control {
        group,
        id,
        label,
        kind,
        hint,
    }
}

const fn step(min: i32, max: i32, step: i32, unit: &'static str) -> Kind {
    Kind::Step {
        min,
        max,
        _step: step,
        unit,
    }
}


pub fn ir_field(id: &str) -> Option<(usize, &str)> {
    let (channel, field) = id.strip_prefix("exp.ir")?.split_once('.')?;
    let channel: usize = channel.parse().ok()?;
    (channel < 2).then_some((channel, field))
}

